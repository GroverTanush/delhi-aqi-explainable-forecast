"""
dashboard/pages/overview.py
Page 1: Overview Dashboard
Main landing page demonstrating current status, latest observed AQI, 5-day forecast,
interactive trajectory chart, project statistics, and key empirical ML insights.
"""

import pandas as pd
import streamlit as st

from dashboard.components import (
    render_header,
    render_freshness_banner,
    render_category_pill,
    render_forecast_card,
    render_alert_box,
)
from dashboard.data_service import get_dataset_summary, get_clean_daily
from dashboard.prediction_service import generate_forecast
from dashboard.charts import create_forecast_figure


def render():
    summary = get_dataset_summary()
    daily_df = get_clean_daily()

    # 1. Page Header
    render_header(
        title="Delhi AQI Intelligence",
        subtitle="Understanding, forecasting and explaining Delhi's air pollution using Machine Learning.",
        badge="Academic ML Research Dashboard",
    )

    # 2. Prominent Freshness Banner
    render_freshness_banner(summary["latest_date_str"])

    # 3. Latest Observed AQI & Current Telemetry
    st.markdown("### Latest Observed Air Quality")
    col_aqi, col_pm25, col_pm10, col_poll = st.columns([1.5, 1, 1, 1])

    with col_aqi:
        pill = render_category_pill(summary["latest_category"], summary["latest_aqi"])
        st.markdown(
            f"""
            <div class="aqi-card" style="border-left: 4px solid #246B57;">
                <div class="aqi-card-header">Latest Observed AQI</div>
                <div class="aqi-card-value">{summary['latest_aqi']:.0f}</div>
                <div>{pill}</div>
                <div class="aqi-card-subtext" style="margin-top: 0.4rem;">
                    Observed on: <strong>{summary['latest_date_str']}</strong>
                </div>
            </div>
            """,
            unsafe_allow_html=True,
        )

    with col_pm25:
        st.markdown(
            f"""
            <div class="aqi-card">
                <div class="aqi-card-header">PM2.5 (Fine)</div>
                <div class="aqi-card-value">{summary['latest_pm25']:.1f} <span style="font-size: 0.8rem; color: #6C7770;">µg/m³</span></div>
                <div class="aqi-card-subtext">24h City Mean</div>
                <div style="font-size: 0.72rem; color: #6C7770; margin-top: 0.25rem;">CPCB Standard: 60</div>
            </div>
            """,
            unsafe_allow_html=True,
        )

    with col_pm10:
        st.markdown(
            f"""
            <div class="aqi-card">
                <div class="aqi-card-header">PM10 (Coarse)</div>
                <div class="aqi-card-value">{summary['latest_pm10']:.1f} <span style="font-size: 0.8rem; color: #6C7770;">µg/m³</span></div>
                <div class="aqi-card-subtext">24h City Mean</div>
                <div style="font-size: 0.72rem; color: #6C7770; margin-top: 0.25rem;">CPCB Standard: 100</div>
            </div>
            """,
            unsafe_allow_html=True,
        )

    with col_poll:
        prominent = str(summary["latest_row"].get("prominent_pollutant", "pm10")).upper()
        st.markdown(
            f"""
            <div class="aqi-card">
                <div class="aqi-card-header">Prominent Pollutant</div>
                <div class="aqi-card-value" style="color: #246B57;">{prominent}</div>
                <div class="aqi-card-subtext">Highest Sub-Index</div>
                <div style="font-size: 0.72rem; color: #6C7770; margin-top: 0.25rem;">Spatial Average across 35 Stns</div>
            </div>
            """,
            unsafe_allow_html=True,
        )

    st.markdown("---")

    # 4. Five-Day Multi-Horizon Forecast from Latest Date
    st.markdown("### Five-Day Multi-Horizon AQI Forecast")
    st.caption(f"Generated by trained Random Forest models (rf_h1.pkl to rf_h5.pkl) using trailing features ending {summary['latest_date_str']}.")

    forecast_df, _, any_alert = generate_forecast(summary["latest_date_str"])

    # High Pollution Alert Banner
    if any_alert:
        alert_days = [f"{r['horizon']} ({r['target_date']})" for _, r in forecast_df.iterrows() if r["predicted_aqi"] > 200]
        render_alert_box(
            title="High Pollution Episode Forecasted (AQI > 200)",
            message=f"Model predicts Poor or worse air quality on: <strong>{', '.join(alert_days)}</strong>. "
                    f"Sensitive individuals should plan to minimize prolonged outdoor exposure.",
            is_warning=True,
        )

    # 5 Forecast Cards
    fcols = st.columns(5)
    for i, (_, row) in enumerate(forecast_df.iterrows()):
        with fcols[i]:
            render_forecast_card(row.to_dict())

    # 5. Interactive Trajectory Chart
    st.markdown("#### Forecast Trajectory vs. Recent History")
    fig = create_forecast_figure(daily_df, summary["end_dt"], forecast_df)
    st.plotly_chart(fig, use_container_width=True)

    st.markdown("---")

    # 6. Verified Project Statistics Grid
    st.markdown("### Project & Dataset Scope")
    st.caption("Empirical dimensions rigorously audited from raw CPCB hourly observations and reproducible pipeline.")

    scol1, scol2, scol3, scol4, scol5, scol6 = st.columns(6)

    stats = [
        ("2018–2026", "Temporal Coverage"),
        (f"{summary['num_stations']}", "Retained Stations"),
        (f"{summary['valid_aqi_days']:,}", "Valid Daily AQI"),
        (f"{summary['num_features']}", "Engineered Features"),
        (f"{summary['forecast_horizons']}", "Forecast Horizons"),
        (f"{summary['evaluation_samples']}", "Test Samples (Days)"),
    ]

    for col, (val, label) in zip([scol1, scol2, scol3, scol4, scol5, scol6], stats):
        with col:
            st.markdown(
                f"""
                <div class="stat-pill">
                    <div class="stat-pill-num">{val}</div>
                    <div class="stat-pill-label">{label}</div>
                </div>
                """,
                unsafe_allow_html=True,
            )

    st.markdown("<br>", unsafe_allow_html=True)

    # 7. Key Scientific Insight
    st.markdown(
        """
        <div style="background-color: #FFFFFF; border: 1px solid #E3E8E2; border-left: 4px solid #246B57; border-radius: 6px; padding: 1rem 1.25rem;">
            <div style="font-weight: 600; font-size: 0.95rem; color: #202923; margin-bottom: 0.35rem;">
                Key Scientific Finding: Attribution Shift Across Forecast Horizons
            </div>
            <div style="font-size: 0.85rem; color: #4A554E; line-height: 1.5;">
                SHAP analysis reveals that for Day +1 (h=1), <strong>90.3%</strong> of total model attribution is driven by immediate pollutant concentrations and 
                recent AQI lags. However, by Day +5 (h=5), attribution dynamically transitions toward cyclical <strong>calendar seasonality (30.7%)</strong> 
                and multi-day smoothed trends. At Day +1, Random Forest achieves an MAE of <strong>27.57</strong> (an 11.0% improvement over Persistence). 
                At longer horizons (h=2 to h=4), moving-block bootstrap confidence intervals confirm that Random Forest performs 
                <strong>statistically indistinguishably</strong> from Damped Anomaly Persistence.
            </div>
        </div>
        """,
        unsafe_allow_html=True,
    )
